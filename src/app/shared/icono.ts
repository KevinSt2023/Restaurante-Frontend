interface Figura { tipo: 'p' | 'c' | 'r'; d?: string; n?: number[]; }

@Component({
  selector: 'vf-icono',
  changeDetection: ChangeDetectionStrategy.OnPush,
  host: { class: 'inline-flex shrink-0', '[style.width.px]': 'tam()', '[style.height.px]': 'tam()', 'aria-hidden': 'true' },
  template: `
    <svg viewBox="0 0 24 24" [attr.width]="tam()" [attr.height]="tam()" fill="none" stroke="currentColor"
         [attr.stroke-width]="grosor()" stroke-linecap="round" stroke-linejoin="round">
      @for (f of figuras(); track $index) {
        @switch (f.tipo) {
          @case ('p') { <path [attr.d]="f.d" /> }
          @case ('c') { <circle [attr.cx]="f.n![0]" [attr.cy]="f.n![1]" [attr.r]="f.n![2]" /> }
          @case ('r') { <rect [attr.x]="f.n![0]" [attr.y]="f.n![1]" [attr.width]="f.n![2]" [attr.height]="f.n![3]" [attr.rx]="f.n![4]" /> }
        }
      }
    </svg>`,
})
export class Icono {
  nombre = input.required<string>();
  tam = input(20);
  grosor = input(2);

  figuras = computed<Figura[]>(() =>
    (ICONOS[this.nombre()] ?? ICONOS['info']).map(s => {
      if (s.startsWith('c:')) return { tipo: 'c', n: s.slice(2).split(',').map(Number) };
      if (s.startsWith('r:')) return { tipo: 'r', n: s.slice(2).split(',').map(Number) };
      return { tipo: 'p', d: s };
    })
  );
}
